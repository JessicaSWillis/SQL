-- 16

SELECT 
    PUBLISHER,
    AVG(PRICE) AS AVG_PRICE
FROM PRODUCTLIST
GROUP BY PUBLISHER
ORDER BY PUBLISHER ASC;

-- 17

CREATE OR REPLACE VIEW OLD_PRODUCT_DISCOUNTS AS
SELECT 
    PRODUCTNAME,
    PRICE * 0.75 AS DISCOUNTED_PRICE
FROM PRODUCTLIST
WHERE RELEASEDATE < ADD_MONTHS(SYSDATE, -60);

SELECT * FROM OLD_PRODUCT_DISCOUNTS

-- 18

SELECT 
    GENRE,
    MAX(PRICE) AS MAX_PRICE,
    MIN(PRICE) AS MIN_PRICE
FROM PRODUCTLIST
GROUP BY GENRE;

