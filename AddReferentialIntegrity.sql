-- 2

SELECT 
    FIRSTNAME || ' ' || LASTNAME AS FULL_NAME,
    USERNAME
FROM USERBASE
WHERE FLOOR(MONTHS_BETWEEN(SYSDATE, BIRTHDAY) / 12) >= 18;

-- 3

SELECT 
    MAX(LENGTH(USERNAME)) AS MAX_USERNAME_LENGTH,
    ROUND(AVG(LENGTH(USERNAME)), 2) AS AVG_USERNAME_LENGTH
FROM USERBASE;

-- 4

SELECT QUESTION
FROM SECURITYQUESTION
WHERE LOWER(QUESTION) LIKE 'what is%'
   OR LOWER(QUESTION) LIKE 'what was%';

-- 5

SELECT 
    PRODUCTCODE,
    MIN(RATING) AS LOWEST_RATING,
    MAX(RATING) AS HIGHEST_RATING,
    TRUNC(AVG(RATING)) AS AVG_RATING,
    COUNT(*) AS REVIEW_COUNT
FROM REVIEWS
GROUP BY PRODUCTCODE
ORDER BY REVIEW_COUNT DESC;

