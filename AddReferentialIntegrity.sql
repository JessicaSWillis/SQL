CREATE OR REPLACE VIEW USER_INFRACTION_COUNTS AS
SELECT 
    USERID,
    COUNT(*) AS INFRACTION_COUNT
FROM INFRACTIONS
GROUP BY USERID
ORDER BY COUNT(*) DESC;

SELECT * FROM USER_INFRACTION_COUNTS

-- 11

CREATE OR REPLACE VIEW USER_RULE_INFRACTION_COUNTS AS
SELECT 
    USERID,
    RULENUM,
    COUNT(*) AS INFRACTION_COUNT
FROM INFRACTIONS
GROUP BY USERID, RULENUM;

SELECT * FROM USER_RULE_INFRACTION_COUNTS

-- 12

SELECT 
    RULENUM,
    PENALTY,
    COUNT(*) AS PENALTY_COUNT
FROM INFRACTIONS
GROUP BY RULENUM, PENALTY;

-- 13

SELECT 
    AVG(DATEUPDATED - DATESUBMITTED) AS AVG_TURNAROUND_DAYS,
    MAX(DATEUPDATED - DATESUBMITTED) AS MAX_TURNAROUND_DAYS,
    MIN(DATEUPDATED - DATESUBMITTED) AS MIN_TURNAROUND_DAYS
FROM USERSUPPORT
WHERE STATUS = 'CLOSED';

-- 14

SELECT 
    EMAIL,
    ISSUE,
    DATESUBMITTED,
    COUNT(*) AS ISSUE_COUNT
FROM USERSUPPORT
WHERE STATUS = 'NEW'
GROUP BY EMAIL, ISSUE, DATESUBMITTED
ORDER BY ISSUE_COUNT DESC;

