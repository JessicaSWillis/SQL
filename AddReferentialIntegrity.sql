CREATE OR REPLACE VIEW RECENT_PENALTIES AS
SELECT 
    USERID,
    DATEASSIGNED,
    PENALTY
FROM INFRACTIONS
WHERE PENALTY IS NOT NULL
  AND DATEASSIGNED >= ADD_MONTHS(SYSDATE, -1);

SELECT * FROM RECENT_PENALTIES