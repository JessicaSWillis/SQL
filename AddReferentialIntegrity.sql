CREATE OR REPLACE VIEW RECENT_CHATLOG AS
SELECT *
FROM CHATLOG
WHERE DATESENT BETWEEN (SYSDATE - 7) AND SYSDATE;

SELECT * FROM RECENT_CHATLOG

